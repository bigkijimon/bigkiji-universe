'use strict';

// The corpus of what the owner actually asked for.
//
// `corpus-ingest.js` was written complete and never called. Measured 2026-08-09: no file
// in src/ or tools/ referenced it, and `owner-turns.jsonl` did not exist — so the only
// record of how this owner phrases a request sat unread across four CLIs while the
// classifier guessed. It is wired to the daemon now, and what has to stay true is:
//
//   it reads only the owner, redacts before writing, never touches the transcripts, and
//   a second pass costs one stat per unchanged file.
//
// Fixtures rather than the real machine, so this passes on a fresh checkout and so the
// assertions can be exact. The live numbers live in `tools/corpus-report.js`.

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { CorpusIngest, ADAPTERS, isOwnerText, flattenContent, sourceRoots } = require('../src/domain/pi-core/corpus-ingest');

let failures = 0;
const ok = (name, body) => { try { body(); console.log(`  ok  ${name}`); } catch (error) { failures += 1; console.error(`  FAIL ${name}\n       ${error.message}`); } };
const okAsync = async (name, body) => { try { await body(); console.log(`  ok  ${name}`); } catch (error) { failures += 1; console.error(`  FAIL ${name}\n       ${error.message}`); } };

const home = fs.mkdtempSync(path.join(os.tmpdir(), 'bigkiji-corpus-'));
const write = (file, rows) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${rows.map((row) => JSON.stringify(row)).join('\n')}\n`);
};

// One file per source, in each vendor's real shape.
write(path.join(home, '.claude', 'projects', 'a', 'session.jsonl'), [
  { type: 'user', message: { role: 'user', content: 'READMEのタイポを直して' } },
  { type: 'user', message: { role: 'user', content: [{ type: 'text', text: 'テストも回して' }] } },
  { type: 'assistant', message: { role: 'assistant', content: 'わかりました' } },
]);
write(path.join(home, '.codex', 'history.jsonl'), [{ text: 'ビルドを通して' }, { text: '' }]);
write(path.join(home, '.pi', 'agent', 'sessions', 's.jsonl'), [
  { type: 'message', message: { role: 'user', content: 'ログを調べておいて' } },
  { type: 'message', message: { role: 'assistant', content: '見ます' } },
]);
write(path.join(home, 'BigKijiUniverse', 'sessions', 'x.jsonl'), [
  { type: 'conversation', role: 'owner', text: 'スキルの一覧を出して' },
  { type: 'conversation', role: 'assistant', text: 'はい' },
  { type: 'conversation', role: 'owner', text: 'READMEのタイポを直して' }, // 別CLIと同一文＝重複
]);

const corpusRoot = path.join(home, 'corpus');
const read = () => fs.readFileSync(path.join(corpusRoot, 'owner-turns.jsonl'), 'utf8')
  .split('\n').filter(Boolean).map((line) => JSON.parse(line));

(async () => {
  ok('four CLIs, four shapes, one reader', () => {
    assert.equal(ADAPTERS.claude({ type: 'user', message: { role: 'user', content: 'x' } }), 'x');
    assert.equal(ADAPTERS.claude({ type: 'assistant', message: { role: 'assistant', content: 'x' } }), '',
      'the assistant is not the owner');
    assert.equal(ADAPTERS.codex({ text: 'x' }), 'x');
    assert.equal(ADAPTERS.pi({ type: 'message', message: { role: 'user', content: 'x' } }), 'x');
    assert.equal(ADAPTERS.bigkiji({ type: 'conversation', role: 'owner', text: 'x' }), 'x');
    assert.equal(ADAPTERS.bigkiji({ type: 'conversation', role: 'assistant', text: 'x' }), '');
    assert.equal(flattenContent([{ type: 'text', text: 'a' }, { type: 'text', text: 'b' }]), 'a\nb',
      'blocks are separate lines of one turn, not one run-on sentence');
    assert.equal(flattenContent([{ type: 'text', text: 'a' }, { type: 'image', source: {} }]), 'a',
      'an image is not the owner talking');
  });

  ok('what Claude Code writes under the owner’s own role is not the owner', () => {
    // The `user` role carries hook output, command results, reminders and the caveat
    // banner. Ingesting those would teach BigKiji its own scaffolding as if the owner
    // had asked for it.
    for (const machine of [
      '<system-reminder>Do not mention this</system-reminder>',
      '<local-command-stdout>ok</local-command-stdout>',
      'Caveat: The messages below were generated by the user while running local commands.',
      '[Request interrupted by user]',
    ]) assert.equal(isOwnerText(machine), false, `machine text: ${machine.slice(0, 40)}`);
    assert.equal(isOwnerText('READMEのタイポを直して'), true);
    assert.equal(isOwnerText(''), false);
    assert.equal(isOwnerText('   '), false);
    // A known cost of the noise filter: MIN_CHARS is 4, so the shortest real Japanese
    // instructions are dropped along with the junk. 「直して」 is three characters and a
    // complete request. Recorded rather than hidden — the corpus under-counts short turns.
    assert.equal(isOwnerText('直して'), false, 'MIN_CHARS=4 drops three-character instructions');
    assert.equal(isOwnerText('はい'), false);
  });

  ok('the sources are the four CLIs, and the daemon root is injectable', () => {
    const roots = sourceRoots(home, path.join(home, 'elsewhere'));
    assert.deepEqual(roots.map((r) => r.id), ['claude', 'codex', 'pi', 'bigkiji']);
    assert.equal(roots[3].dir, path.join(home, 'elsewhere', 'sessions'),
      'the data root moves, so this cannot be hardcoded to ~/BigKijiUniverse');
  });

  await okAsync('one pass collects every owner turn and nothing else', async () => {
    const summary = await new CorpusIngest({ corpusRoot, home }).run();
    const rows = read();
    const texts = rows.map((r) => r.text).sort();
    assert.deepEqual(texts, ['READMEのタイポを直して', 'スキルの一覧を出して', 'テストも回して', 'ビルドを通して', 'ログを調べておいて'],
      `owner turns only, deduplicated: ${JSON.stringify(texts)}`);
    assert.equal(summary.added, 5);
    assert.equal(summary.total, 5);
    assert.deepEqual(Object.keys(summary.bySource).sort(), ['bigkiji', 'claude', 'codex', 'pi']);
    // The same instruction in two transcripts is one instruction. Without this, a resumed
    // session turns repetition into emphasis.
    assert.equal(rows.filter((r) => r.text === 'READMEのタイポを直して').length, 1);
    assert.ok(rows.every((r) => r.file.startsWith('~/')), 'paths are recorded relative to home, not absolute');
  });

  await okAsync('a second pass reads nothing and adds nothing', async () => {
    const summary = await new CorpusIngest({ corpusRoot, home }).run();
    assert.equal(summary.added, 0, 'nothing changed on disk, so nothing may be appended');
    assert.equal(summary.skipped, summary.scanned, 'and every file is skipped on its stat alone');
    assert.equal(read().length, 5, 'the file must not double');
  });

  await okAsync('a changed file is re-read, and only the new lines land', async () => {
    const file = path.join(home, '.codex', 'history.jsonl');
    fs.appendFileSync(file, `${JSON.stringify({ text: 'デプロイして' })}\n`);
    const summary = await new CorpusIngest({ corpusRoot, home }).run();
    assert.equal(summary.added, 1, `only the appended turn: ${summary.added}`);
    assert.ok(read().some((r) => r.text === 'デプロイして'));
  });

  await okAsync('a secret is redacted before it is written, not after', async () => {
    const secretHome = fs.mkdtempSync(path.join(os.tmpdir(), 'bigkiji-corpus-secret-'));
    write(path.join(secretHome, '.codex', 'history.jsonl'), [
      { text: 'この鍵を使って: sk-ant-api03-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA' },
    ]);
    const root = path.join(secretHome, 'corpus');
    await new CorpusIngest({ corpusRoot: root, home: secretHome }).run();
    const body = fs.readFileSync(path.join(root, 'owner-turns.jsonl'), 'utf8');
    assert.ok(!/sk-ant-api03-A{20}/.test(body),
      'the corpus outlives the transcript it came from, so a key must never reach it');
    fs.rmSync(secretHome, { recursive: true, force: true });
  });

  ok('the transcripts it reads are never modified', () => {
    // The whole design rests on this: the corpus is derived, the CLIs own their history.
    const source = fs.readFileSync(path.join(__dirname, '..', 'src', 'domain', 'pi-core', 'corpus-ingest.js'), 'utf8');
    const writes = source.match(/fs\.(?:write|append|rm|unlink|rename|copy)[A-Za-z]*\(([^,)]+)/g) || [];
    for (const call of writes) {
      assert.ok(/this\.(?:turnsFile|stateFile|corpusRoot)|corpusRoot|tmp/.test(call),
        `every write must target the corpus directory: ${call}`);
    }
    assert.ok(/mkdirSync\(this\.corpusRoot/.test(source), 'and it creates only its own directory');
  });

  await okAsync('the daemon starts it, deferred, into ITS OWN root', async () => {
    // The suite sets BIGKIJI_SKIP_CORPUS so 65 other selftests do not each kick off a scan
    // of ~/.claude/projects. This one check is about the scheduling, so it lifts the skip
    // for itself and puts it back.
    const skip = process.env.BIGKIJI_SKIP_CORPUS; delete process.env.BIGKIJI_SKIP_CORPUS;
    try {
      const { DaemonEngine } = require('../src/domain/server/daemon');
      const stateRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'bigkiji-corpus-daemon-'));
      const engine = new DaemonEngine({ stateRoot, workspace: process.cwd() });
      // Deferred: the first pass reads every transcript on the machine, and the daemon has
      // to be answering turns before that finishes.
      assert.ok(engine.corpusTimer, 'the daemon schedules an ingest');
      // And it must land inside the injected root. A corpus root derived from the real
      // data layout would have the suite writing into the owner's own corpus — the same
      // shape of mistake that destroyed 300 events of task_state.json history.
      assert.ok(engine.corpusRoot.startsWith(stateRoot),
        `the corpus follows the injected stateRoot: ${engine.corpusRoot}`);
      engine.shutdown();
      const again = new DaemonEngine({ stateRoot, workspace: process.cwd() });
      assert.equal(again.ingestCorpus(), null, 'an ingest already scheduled is not scheduled twice');
      again.shutdown();
      fs.rmSync(stateRoot, { recursive: true, force: true });
    } finally { if (skip !== undefined) process.env.BIGKIJI_SKIP_CORPUS = skip; }
  });

  fs.rmSync(home, { recursive: true, force: true });
  if (failures) { console.error(`corpus selftest: ${failures} FAILED`); process.exit(1); }
  console.log('corpus selftest: PASS · four CLI shapes · owner turns only · deduplicated across transcripts · '
    + 'incremental on stat alone · secrets redacted before writing · the transcripts are never touched · '
    + 'the daemon schedules it once, deferred');
})().catch((error) => { console.error(error); process.exit(1); });
