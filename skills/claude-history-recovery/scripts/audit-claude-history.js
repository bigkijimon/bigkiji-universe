#!/usr/bin/env node
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const readline = require('readline');

let redactPayload = (value) => ({ text: String(value || ''), blocked: false });
try {
  ({ redactPayload } = require('../../../src/domain/pi-core/security/payload-redactor'));
} catch (_) {
  // The script remains useful if the skill is copied outside the BKU source tree.
}

const MACHINE_MARKERS = [
  '<system-reminder>', '<local-command-stdout>', '<local-command-caveat>',
  '<command-name>', '<command-message>', '<command-args>', '<task-notification>',
  'Caveat: The messages below were generated by the user while running',
  'This session is being continued from a previous conversation that ran out of context.',
  '[Request interrupted', 'This is an automated background-task event', 'tool_use_id',
  '/compact', '/clear',
];

function usage(message = '') {
  if (message) process.stderr.write(`${message}\n\n`);
  process.stderr.write([
    'Usage: audit-claude-history.js [options]',
    '  --root PATH         Claude projects root (default: ~/.claude/projects)',
    '  --since DATE        Include files modified on/after DATE',
    '  --format FORMAT     markdown or json (default: markdown)',
    '  --limit N           Maximum sessions after sorting (default: 50)',
    '  --output PATH       Write the derived report to PATH instead of stdout',
  ].join('\n') + '\n');
  process.exit(message ? 2 : 0);
}

function parseArgs(argv) {
  const options = {
    root: path.join(os.homedir(), '.claude', 'projects'),
    since: 0,
    format: 'markdown',
    limit: 50,
    output: '',
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--help' || arg === '-h') usage();
    if (!['--root', '--since', '--format', '--limit', '--output'].includes(arg)) usage(`Unknown option: ${arg}`);
    const value = argv[++i];
    if (!value) usage(`Missing value for ${arg}`);
    if (arg === '--root') options.root = path.resolve(value);
    if (arg === '--since') {
      const parsed = Date.parse(value);
      if (!Number.isFinite(parsed)) usage(`Invalid date: ${value}`);
      options.since = parsed;
    }
    if (arg === '--format') options.format = value;
    if (arg === '--limit') options.limit = Number(value);
    if (arg === '--output') options.output = path.resolve(value);
  }
  if (!['markdown', 'json'].includes(options.format)) usage('--format must be markdown or json');
  if (!Number.isInteger(options.limit) || options.limit < 1) usage('--limit must be a positive integer');
  return options;
}

function listJsonl(root) {
  const found = [];
  const stack = [root];
  while (stack.length) {
    const current = stack.pop();
    let entries = [];
    try { entries = fs.readdirSync(current, { withFileTypes: true }); } catch (_) { continue; }
    for (const entry of entries) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'subagents') stack.push(full);
      } else if (entry.isFile() && entry.name.endsWith('.jsonl')) {
        found.push(full);
      }
    }
  }
  return found;
}

function flatten(content) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  return content.filter((part) => part && part.type === 'text').map((part) => part.text || '').join('\n');
}

function cleanExcerpt(value, max = 360) {
  const compact = String(value || '').replace(/[\r\n\t]+/g, ' ').replace(/\s+/g, ' ').trim();
  const redacted = redactPayload(compact, { blockCritical: true });
  if (redacted.blocked) return '<BLOCKED:critical-secret>';
  return redacted.text.slice(0, max);
}

function isOwnerText(text) {
  const value = String(text || '').trim();
  return value.length >= 4 && !MACHINE_MARKERS.some((marker) => value.includes(marker));
}

async function audit(file, root) {
  const stat = fs.statSync(file);
  const summary = {
    sessionId: path.basename(file, '.jsonl'),
    source: path.relative(root, file),
    bytes: stat.size,
    modifiedAt: stat.mtime.toISOString(),
    lastEventAt: null,
    cwd: null,
    ownerTurns: 0,
    assistantTurns: 0,
    lastOwner: '',
    lastAssistant: '',
    signals: { interrupted: false, compacted: false, sessionLimit: false },
  };
  const lines = readline.createInterface({ input: fs.createReadStream(file, 'utf8'), crlfDelay: Infinity });
  for await (const line of lines) {
    let row;
    try { row = JSON.parse(line); } catch (_) { continue; }
    if (row.sessionId) summary.sessionId = row.sessionId;
    if (row.cwd) summary.cwd = row.cwd;
    if (row.timestamp) summary.lastEventAt = row.timestamp;
    const text = flatten(row.message && row.message.content);
    if (text.includes('[Request interrupted')) summary.signals.interrupted = true;
    if (text.includes('<command-name>/compact') || text.trim() === '/compact') summary.signals.compacted = true;
    if (/session limit/i.test(text)) summary.signals.sessionLimit = true;
    if (row.type === 'user' && row.message && row.message.role === 'user' && isOwnerText(text)) {
      summary.ownerTurns += 1;
      summary.lastOwner = cleanExcerpt(text);
    }
    if (row.type === 'assistant' && row.message && row.message.role === 'assistant' && text.trim()) {
      summary.assistantTurns += 1;
      summary.lastAssistant = cleanExcerpt(text);
    }
  }
  return summary;
}

function size(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

function cell(value) {
  return String(value == null ? '' : value).replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');
}

function markdown(rows, options) {
  const lines = [
    '# Claude Code history audit',
    '',
    `Generated: ${new Date().toISOString()}`,
    `Source: ${options.root}`,
    '',
    '> This is a derived, redacted index. Raw JSONL files were not modified.',
    '',
    '| modified | session | cwd | turns | signals | last owner instruction | last assistant text |',
    '|---|---|---|---:|---|---|---|',
  ];
  for (const row of rows) {
    const signals = Object.entries(row.signals).filter(([, yes]) => yes).map(([name]) => name).join(', ');
    lines.push(`| ${cell(row.modifiedAt)} | ${cell(row.sessionId)} (${size(row.bytes)}) | ${cell(row.cwd)} | ${row.ownerTurns}/${row.assistantTurns} | ${cell(signals)} | ${cell(row.lastOwner)} | ${cell(row.lastAssistant)} |`);
  }
  return `${lines.join('\n')}\n`;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const candidates = listJsonl(options.root)
    .map((file) => ({ file, stat: fs.statSync(file) }))
    .filter(({ stat }) => stat.mtimeMs >= options.since)
    .sort((a, b) => b.stat.mtimeMs - a.stat.mtimeMs)
    .slice(0, options.limit);
  const rows = [];
  for (const { file } of candidates) rows.push(await audit(file, options.root));
  const rendered = options.format === 'json'
    ? `${JSON.stringify({ generatedAt: new Date().toISOString(), root: options.root, sessions: rows }, null, 2)}\n`
    : markdown(rows, options);
  if (options.output) {
    fs.mkdirSync(path.dirname(options.output), { recursive: true });
    fs.writeFileSync(options.output, rendered);
    process.stdout.write(`${options.output}\n`);
  } else {
    process.stdout.write(rendered);
  }
}

main().catch((error) => {
  process.stderr.write(`${error.stack || error.message}\n`);
  process.exit(1);
});
